void main() {
  // int adalah tipe data yang dapat menyimpan bilangan bulat.

  // Contoh penggunaan int lainnya:
  int umur = 20;
  int tahunLahir = 2004;
  int nim = 221240001238;
  print('Umur saya: $umur tahun');
  print('Saya lahir tahun: $tahunLahir');
  print('NIM saya: $nim');

  // Operasi aritmatika dengan int
  int a = 10;
  int b = 5;
  print('Hasil penjumlahan: ${a + b}');
  print('Hasil pengurangan: ${a - b}');
  print('Hasil perkalian: ${a * b}');
  print('Hasil pembagian: ${a ~/ b}'); // Pembagian dengan hasil bulat
}



