void main() {
  bool isTrue = true;
  bool isFalse = false;

  print('Nilai boolean: $isTrue');
  print('Nilai boolean: $isFalse');

  // Operasi boolean
  bool a = true;
  bool b = false;

  print('Hasil AND: ${a && b}');
  print('Hasil NOT: ${!a}');

  // Contoh penggunaan boolean lainnya
  bool isLoggedIn = true;
  bool isAdmin = false;

  print('Status login: $isLoggedIn');
  print('Status admin: $isAdmin');

  // Operasi boolean dengan variabel
  bool hasPermission = isLoggedIn && isAdmin;
  print('Memiliki izin: $hasPermission');



}



