void main() {
// double adalah tipe data yang dapat menyimpan bilangan desimal
  double harga = 15000.50;
  double suhu = -5.5;
  double jarak = 3.14;
  double nilaiPi = 3.14159;
  double nilaiIlmiah = 6.022e23; // Notasi eksponensial

  print('Harga barang: Rp $harga');
  print('Suhu: $suhu derajat Celsius'); 
  print('Jarak: $jarak kilometer');
  print('Nilai Pi: $nilaiPi');
  print('Bilangan ilmiah: $nilaiIlmiah');

  // Operasi matematika dengan double
  double a = 10.5;
  double b = 3.2;
  print('Hasil penjumlahan: ${a + b}');
  print('Hasil pengurangan: ${a - b}');
  print('Hasil perkalian: ${a * b}');
  print('Hasil pembagian: ${a / b}');


}


  